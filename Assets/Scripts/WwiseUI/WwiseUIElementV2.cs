using UnityEngine;
using UnityEngine.UI;
using UnityEngine.EventSystems;

/// <summary>
/// Gold Standard UI Audio Component (V2)
/// 
/// Consolidated component that handles audio feedback for ALL UI elements:
/// - Buttons (simple switch)
/// - Sliders (simple switch for selection - use WwiseRtpcSliderV2 for RTPC control)
/// - Toggles (state-based switches + action audio)
/// - Main Menu Buttons (context-aware switching based on navigation source)
/// 
/// NAVIGATION MODEL:
/// This system is designed for keyboard-only navigation by blind users:
/// - Arrow keys: Navigate between UI elements (triggers OnSelect ? selection audio)
/// - Enter key: Activate/toggle elements (triggers onValueChanged ? action audio for toggles)
/// - NO mouse interaction
/// 
/// REPLACES: WwiseObstacleToggle, WwiseMainMenuButton
/// ENHANCES: Original WwiseUIElement
/// 
/// This component posts all audio through the AudioEventChannelSO, ensuring
/// proper sequencing and priority handling via the AudioManager.
/// </summary>
public class WwiseUIElementV2 : MonoBehaviour, ISelectHandler
{
    // ???????????????????????????????????????????????????????????????????
    // INSPECTOR FIELDS
    // ???????????????????????????????????????????????????????????????????

    [Header("Audio Channel")]
    [Tooltip("Reference to the shared AudioEventChannelSO (e.g., 'UIAudioChannel')")]
    public AudioEventChannelSO audioChannel;

    [Header("Selection Audio")]
    [Tooltip("The Wwise event to play when this element is selected/highlighted")]
    public AK.Wwise.Event selectionEvent;

    // ???????????????????????????????????????????????????????????????????
    // SWITCH MODE 1: Simple Switch (Buttons, Sliders, etc.)
    // ???????????????????????????????????????????????????????????????????
    [Header("Switch Mode 1: Simple (Buttons/Sliders)")]
    [Tooltip("Use this for elements that always use the same switch (buttons, sliders, non-state toggles)")]
    public AK.Wwise.Switch simpleSwitch;

    // ???????????????????????????????????????????????????????????????????
    // SWITCH MODE 2: Context-Based (Main Menu Navigation)
    // ???????????????????????????????????????????????????????????????????
    [Header("Switch Mode 2: Context-Based (Main Menu)")]
    [Tooltip("Enable this for main menu buttons that need different audio based on how the menu was opened")]
    public bool useReturnContext = false;

    [Tooltip("Switch to use when navigating normally (e.g., menu opened fresh with 'N' key)")]
    public AK.Wwise.Switch normalSwitch;

    [Tooltip("Switch to use when returning from a subwindow")]
    public AK.Wwise.Switch returnContextSwitch;

    // ???????????????????????????????????????????????????????????????????
    // SWITCH MODE 3: Toggle State-Based (Toggles)
    // ???????????????????????????????????????????????????????????????????
    [Header("Switch Mode 3: Toggle State (Toggle Selection)")]
    [Tooltip("Switch to use when toggle is checked/ON (only for Toggle elements with state-based audio)")]
    public AK.Wwise.Switch toggleOnSwitch;

    [Tooltip("Switch to use when toggle is unchecked/OFF (only for Toggle elements with state-based audio)")]
    public AK.Wwise.Switch toggleOffSwitch;

    // ???????????????????????????????????????????????????????????????????
    // TOGGLE ACTION AUDIO (Optional)
    // ???????????????????????????????????????????????????????????????????
    [Header("Toggle Action Audio (Optional)")]
    [Tooltip("Event to play when toggle value changes (only plays when user presses Enter to activate, not when set programmatically)")]
    public AK.Wwise.Event toggleActionEvent;

    [Tooltip("Switch for toggle action when checked")]
    public AK.Wwise.Switch actionCheckedSwitch;

    [Tooltip("Switch for toggle action when unchecked")]
    public AK.Wwise.Switch actionUncheckedSwitch;

    // ???????????????????????????????????????????????????????????????????
    // PRIVATE FIELDS
    // ???????????????????????????????????????????????????????????????????

    private Toggle myToggle;
    private bool isCurrentlySelected = false;

    // ???????????????????????????????????????????????????????????????????
    // UNITY LIFECYCLE
    // ???????????????????????????????????????????????????????????????????

    private void Awake()
    {
        // Cache Toggle component reference if this GameObject has one
        myToggle = GetComponent<Toggle>();
    }

    private void OnEnable()
    {
        // Subscribe to toggle value changes if this is a toggle
        if (myToggle != null)
        {
            myToggle.onValueChanged.AddListener(OnToggleValueChanged);
        }
    }

    private void OnDisable()
    {
        // Unsubscribe to prevent memory leaks
        if (myToggle != null)
        {
            myToggle.onValueChanged.RemoveListener(OnToggleValueChanged);
        }
        isCurrentlySelected = false;
    }

    private void Update()
    {
        // Track deselection (Unity doesn't provide OnDeselect for UI elements)
        if (isCurrentlySelected && EventSystem.current.currentSelectedGameObject != this.gameObject)
        {
            isCurrentlySelected = false;
        }
    }

    // ???????????????????????????????????????????????????????????????????
    // EVENT SYSTEM INTERFACE
    // ???????????????????????????????????????????????????????????????????

    /// <summary>
    /// Called by Unity's EventSystem when this UI element is selected/highlighted.
    /// Plays the appropriate selection audio based on the configured switch mode.
    /// </summary>
    public void OnSelect(BaseEventData eventData)
    {
        Debug.Log($"[WwiseUIElementV2] OnSelect called on '{gameObject.name}'");

        isCurrentlySelected = true;

        // Validate required references
        if (audioChannel == null || selectionEvent == null)
        {
            if (audioChannel == null)
                Debug.LogError($"[WwiseUIElementV2] '{gameObject.name}': audioChannel is not assigned!");
            if (selectionEvent == null)
                Debug.LogError($"[WwiseUIElementV2] '{gameObject.name}': selectionEvent is not assigned!");
            return;
        }

        // For context-based mode, check and cache the return flag BEFORE determining switch
        bool wasReturning = false;
        if (useReturnContext)
        {
            AudioManager audioManager = AudioManager.Instance;
            if (audioManager == null)
            {
                Debug.LogError($"[WwiseUIElementV2] '{gameObject.name}': useReturnContext is enabled but AudioManager.Instance is null!");
            }
            else
            {
                wasReturning = audioManager.IsReturningToMainMenu();
                Debug.Log($"[WwiseUIElementV2] '{gameObject.name}': IsReturning = {wasReturning}");
            }
        }

        // Determine which switch to use based on configuration
        AK.Wwise.Switch switchToSend = DetermineSelectionSwitch();

        if (switchToSend == null)
        {
            Debug.LogError($"[WwiseUIElementV2] '{gameObject.name}': No valid switch determined for selection!");
            return;
        }

        Debug.Log($"[WwiseUIElementV2] '{gameObject.name}': Using switch '{switchToSend.Name}'");

        // Create the audio packet
        AudioEventChannelSO.WwiseEventPacket packet = new AudioEventChannelSO.WwiseEventPacket
        {
            WwiseEvent = selectionEvent,
            WwiseSwitch = switchToSend,
            Emitter = this.gameObject
        };

        Debug.Log($"[WwiseUIElementV2] '{gameObject.name}': Raising audio event through channel");

        // Post through the audio channel (AudioManager will handle priority/sequencing)
        audioChannel.RaiseEvent(packet);

        // CRITICAL: Clear the return flag ONLY if it was true when we checked
        // This ensures the return context audio plays only ONCE (on auto-selection after returning)
        if (wasReturning)
        {
            AudioManager audioManager = AudioManager.Instance;
            if (audioManager != null)
            {
                audioManager.SetReturningToMainMenu(false);
                Debug.Log($"[WwiseUIElementV2] '{gameObject.name}': Cleared returning flag");
            }
        }
    }

    // ???????????????????????????????????????????????????????????????????
    // TOGGLE-SPECIFIC LOGIC
    // ???????????????????????????????????????????????????????????????????

    /// <summary>
    /// Called when the toggle value changes.
    /// Only plays action audio if THIS toggle is currently selected (user pressed Enter to activate).
    /// This prevents audio from playing when toggle values are set programmatically.
    /// </summary>
    private void OnToggleValueChanged(bool isOn)
    {
        // Only play action audio if this toggle is currently selected by the user
        if (!isCurrentlySelected) return;

        // Validate references
        if (audioChannel == null || toggleActionEvent == null) return;

        // Determine which action switch to use
        AK.Wwise.Switch actionSwitch = isOn ? actionCheckedSwitch : actionUncheckedSwitch;
        if (actionSwitch == null)
        {
            Debug.LogWarning($"[WwiseUIElementV2] '{gameObject.name}': Action switch not assigned for toggle state {(isOn ? "ON" : "OFF")}");
            return;
        }

        // Create the action audio packet
        AudioEventChannelSO.WwiseEventPacket packet = new AudioEventChannelSO.WwiseEventPacket
        {
            WwiseEvent = toggleActionEvent,
            WwiseSwitch = actionSwitch,
            Emitter = this.gameObject
        };

        // Post through the audio channel
        audioChannel.RaiseEvent(packet);
    }

    // ???????????????????????????????????????????????????????????????????
    // SWITCH SELECTION LOGIC
    // ???????????????????????????????????????????????????????????????????

    /// <summary>
    /// Determines which switch to use for selection audio based on the component's configuration.
    /// 
    /// Priority Order:
    /// 1. Context-based (if useReturnContext is enabled)
    /// 2. Toggle state-based (if this is a Toggle with state switches assigned)
    /// 3. Simple switch (fallback for all other elements)
    /// </summary>
    private AK.Wwise.Switch DetermineSelectionSwitch()
    {
        // ??? MODE 2: Context-Based Switching (Main Menu) ???
        if (useReturnContext)
        {
            AudioManager audioManager = AudioManager.Instance;
            if (audioManager == null)
            {
                Debug.LogError($"[WwiseUIElementV2] '{gameObject.name}': useReturnContext is enabled but AudioManager.Instance is null!");
                return normalSwitch; // Fallback to normal switch
            }

            bool isReturning = audioManager.IsReturningToMainMenu();
            return isReturning ? returnContextSwitch : normalSwitch;
        }

        // ??? MODE 3: Toggle State-Based Switching ???
        if (myToggle != null && toggleOnSwitch != null && toggleOffSwitch != null)
        {
            return myToggle.isOn ? toggleOnSwitch : toggleOffSwitch;
        }

        // ??? MODE 1: Simple Switch (Default) ???
        return simpleSwitch;
    }

    // ???????????????????????????????????????????????????????????????????
    // DEBUG HELPERS (Optional - can be removed in production)
    // ???????????????????????????????????????????????????????????????????

#if UNITY_EDITOR
    private void OnValidate()
    {
        // Provide helpful warnings in the Inspector
        if (useReturnContext && (normalSwitch == null || returnContextSwitch == null))
        {
            Debug.LogWarning($"[WwiseUIElementV2] '{gameObject.name}': useReturnContext is enabled but context switches are not assigned!");
        }

        if (myToggle != null && toggleActionEvent != null && (actionCheckedSwitch == null || actionUncheckedSwitch == null))
        {
            Debug.LogWarning($"[WwiseUIElementV2] '{gameObject.name}': toggleActionEvent is assigned but action switches are missing!");
        }
    }
#endif
}