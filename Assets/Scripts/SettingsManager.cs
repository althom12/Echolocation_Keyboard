#if UNITY_EDITOR
    private void OnValidate()
    {
        // Clamp volume and pitch to valid range
        _footstepVolume = Mathf.Clamp(_footstepVolume, 0f, 100f);
        _footstepPitch = Mathf.Clamp(_footstepPitch, 0f, 100f);

        // Warn if RTPCs are not assigned
        if (footstepVolumeRTPC == null || !footstepVolumeRTPC.IsValid())
        {
            Debug.LogWarning($"[SettingsManager - {gameObject.name}] 'footstepVolumeRTPC' is not assigned! Assign it in the Inspector.");
        }

        if (footstepPitchRTPC == null || !footstepPitchRTPC.IsValid())
        {
            Debug.LogWarning($"[SettingsManager - {gameObject.name}] 'footstepPitchRTPC' is not assigned! Assign it in the Inspector.");
        }
    }

    // Inspector button to test settings at runtime
    [ContextMenu("Test: Enable Footsteps")]
    private void TestEnableFootsteps()
    {
        SetFootstepEnabled(true);
    }

    [ContextMenu("Test: Disable Footsteps")]
    private void TestDisableFootsteps()
    {
        SetFootstepEnabled(false);
    }

    [ContextMenu("Test: Set Volume to 50%")]
    private void TestSetVolume50()
    {
        SetFootstepVolume(0.5f);
    }

    [ContextMenu("Test: Set Volume to 100%")]
    private void TestSetVolume100()
    {
        SetFootstepVolume(1.0f);
    }

    [ContextMenu("Test: Set Pitch to 50%")]
    private void TestSetPitch50()
    {
        SetFootstepPitch(0.5f);
    }

    [ContextMenu("Test: Set Pitch to 100%")]
    private void TestSetPitch100()
    {
        SetFootstepPitch(1.0f);
    }
#endif
}