using UnityEngine;

/// <summary>
/// A persistent MonoBehaviour Singleton that manages all game settings.
/// Provides a central, global "source of truth" for all other systems.
/// Handles loading and saving settings to PlayerPrefs.
/// </summary>
public class SettingsManager : MonoBehaviour
{
    // ???????????????????????????????????????????????????????????
    // SINGLETON (PERSISTENT - Uses DontDestroyOnLoad)
    // ???????????????????????????????????????????????????????????

    /// <summary>
    /// Persistent singleton instance. Survives scene loads.
    /// Settings should persist across all scenes.
    /// </summary>
    public static SettingsManager Instance { get; private set; }

    // ???????????????????????????????????????????????????????????
    // PLAYERPREFS KEYS
    // ???????????????????????????????????????????????????????????

    private static readonly string FootstepsEnabledKey = "Settings_FootstepsEnabled";

    // ???????????????????????????????????????????????????????????
    // PUBLIC SETTINGS PROPERTIES
    // ???????????????????????????????????????????????????????????

    /// <summary>
    /// Is the footstep audio currently enabled? Read by PlayerAudio, Written by UI.
    /// </summary>
    public bool IsFootstepsEnabled { get; set; }

    // ???????????????????????????????????????????????????????????
    // INITIALIZATION
    // ???????????????????????????????????????????????????????????

    /// <summary>
    /// Ensures the SettingsManager is created and loaded before any Awake() calls.
    /// Can be called manually to force initialization if needed.
    /// </summary>
    public static void Initialize()
    {
        if (Instance == null)
        {
            Instance = FindObjectOfType<SettingsManager>();
            if (Instance == null)
            {
                GameObject managerObject = new GameObject("@SettingsManager");
                Instance = managerObject.AddComponent<SettingsManager>();
            }
            // Awake() will handle DontDestroyOnLoad
            Instance.LoadSettings();
        }
    }

    private void Awake()
    {
        // Singleton setup - Persistent (with DontDestroyOnLoad)
        if (Instance == null)
        {
            Instance = this;
            DontDestroyOnLoad(gameObject);
            LoadSettings(); // Load settings if Initialize didn't run (e.g. direct scene start in editor)
        }
        else if (Instance != this)
        {
            Debug.LogWarning($"[SettingsManager] Duplicate instance found on '{gameObject.name}'. Destroying duplicate.");
            Destroy(gameObject);
            return;
        }
    }

    // ???????????????????????????????????????????????????????????
    // PERSISTENCE (SAVING AND LOADING)
    // ???????????????????????????????????????????????????????????

    /// <summary>
    /// Saves all current settings to PlayerPrefs. Called by UI elements.
    /// </summary>
    public void SaveSettings()
    {
        // Convert bool to int for PlayerPrefs
        int footstepsValue = IsFootstepsEnabled ? 1 : 0;
        PlayerPrefs.SetInt(FootstepsEnabledKey, footstepsValue);

        PlayerPrefs.Save();
        Debug.Log($"[SettingsManager] Settings saved. Footsteps enabled: {IsFootstepsEnabled}");
    }

    /// <summary>
    /// Loads all settings from PlayerPrefs. Called only at game launch via Initialize/Awake.
    /// </summary>
    private void LoadSettings()
    {
        // Get the raw value before converting, using 1 (true) as default
        int loadedValue = PlayerPrefs.GetInt(FootstepsEnabledKey, 1);

        // Set the property based on the loaded value
        IsFootstepsEnabled = loadedValue == 1;

        // Log the debug info
        Debug.Log($"[SettingsManager] Loaded raw value for '{FootstepsEnabledKey}' = {loadedValue}. IsFootstepsEnabled set to: {IsFootstepsEnabled}");
    }
}