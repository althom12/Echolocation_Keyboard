using UnityEngine;
using AK.Wwise;

/// <summary>
/// Settings Manager - Single Source of Truth for Game Settings
/// 
/// This Singleton manages the runtime state of all game settings and acts as the bridge
/// between the UI (PageControlItems) and game systems (Wwise, graphics, gameplay).
/// 
/// CRITICAL DESIGN PRINCIPLE: State Persistence
/// The manager stores volume and enabled state SEPARATELY. When a toggle is set to OFF,
/// we send 0 to Wwise but remember the volume setting. When toggled back ON, we restore
/// the previous volume instead of defaulting to 100.
/// 
/// ARCHITECTURE:
/// UI (Slider/Toggle) ? Listener ? SettingsManager ? Wwise/Game Systems
/// 
/// USAGE:
/// 1. Wire PageControlItem.OnValueChanged (slider) ? SettingsManager.SetFootstepVolume(float)
/// 2. Wire PageToggleListener.OnToggleChanged (toggle) ? SettingsManager.SetFootstepEnabled(bool)
/// 
/// The manager handles the logic of combining these two states when updating Wwise.
/// </summary>
public class SettingsManager : MonoBehaviour
{
    // ???????????????????????????????????????????????????????????????????????
    // SINGLETON PATTERN
    // ???????????????????????????????????????????????????????????????????????

    private static SettingsManager _instance;

    public static SettingsManager Instance
    {
        get
        {
            if (_instance == null)
            {
                _instance = FindObjectOfType<SettingsManager>();

                if (_instance == null)
                {
                    GameObject singleton = new GameObject("SettingsManager");
                    _instance = singleton.AddComponent<SettingsManager>();
                    DontDestroyOnLoad(singleton);
                    Debug.Log("[SettingsManager] Instance created and set to DontDestroyOnLoad");
                }
            }
            return _instance;
        }
    }

    // ???????????????????????????????????????????????????????????????????????
    // INSPECTOR FIELDS - WWISE REFERENCES
    // ???????????????????????????????????????????????????????????????????????

    [Header("Wwise RTPC References")]
    [Tooltip("The Wwise RTPC that controls footstep volume (e.g., 'RTPC_FootstepVolume')")]
    public AK.Wwise.RTPC footstepVolumeRTPC;

    [Tooltip("The Wwise RTPC that controls footstep pitch (e.g., 'RTPC_FootstepPitch')")]
    public AK.Wwise.RTPC footstepPitchRTPC;

    [Header("Audio Emitter")]
    [Tooltip("GameObject to emit Wwise events from. If null, uses this GameObject.")]
    public GameObject audioEmitter;

    [Header("Debug")]
    [SerializeField] private bool enableDebugLogs = true;

    // ???????????????????????????????????????????????????????????????????????
    // STATE VARIABLES (SOURCE OF TRUTH)
    // ???????????????????????????????????????????????????????????????????????

    [Header("Footstep Settings State")]
    [SerializeField] private float _footstepVolume = 50f;   // 0-100 range
    [SerializeField] private bool _footstepsEnabled = true;
    [SerializeField] private float _footstepPitch = 50f;    // 0-100 range

    // ???????????????????????????????????????????????????????????????????????
    // UNITY LIFECYCLE
    // ???????????????????????????????????????????????????????????????????????

    private void Awake()
    {
        // Singleton enforcement
        if (_instance != null && _instance != this)
        {
            Debug.LogWarning("[SettingsManager] Duplicate instance detected! Destroying this one.");
            Destroy(gameObject);
            return;
        }

        _instance = this;
        DontDestroyOnLoad(gameObject);

        if (enableDebugLogs)
            Debug.Log($"[SettingsManager] Singleton initialized: Volume={_footstepVolume}, Enabled={_footstepsEnabled}");
    }

    private void Start()
    {
        // Set default audio emitter if not assigned
        if (audioEmitter == null)
        {
            audioEmitter = this.gameObject;

            if (enableDebugLogs)
                Debug.Log($"[SettingsManager] audioEmitter not assigned, using self: {audioEmitter.name}");
        }

        // Validate Wwise references
        if (footstepVolumeRTPC == null || !footstepVolumeRTPC.IsValid())
        {
            Debug.LogError("[SettingsManager] footstepVolumeRTPC is not assigned or invalid! Footstep volume control will not work.");
        }

        if (footstepPitchRTPC == null || !footstepPitchRTPC.IsValid())
        {
            Debug.LogError("[SettingsManager] footstepPitchRTPC is not assigned or invalid! Footstep pitch control will not work.");
        }

        // Initialize Wwise with default values
        ApplyFootstepVolumeToWwise();
        ApplyFootstepPitchToWwise();

        if (enableDebugLogs)
            Debug.Log("[SettingsManager] Initialized Wwise with default settings");
    }

    // ???????????????????????????????????????????????????????????????????????
    // PUBLIC API - FOOTSTEP VOLUME (Called by Slider Listener)
    // ???????????????????????????????????????????????????????????????????????

    /// <summary>
    /// Sets the footstep volume level.
    /// Wire this to PageControlItem.OnValueChanged (slider) in the Inspector.
    /// 
    /// If footsteps are enabled, immediately updates Wwise RTPC.
    /// If footsteps are disabled, stores the value but keeps RTPC at 0.
    /// </summary>
    /// <param name="value">Volume level (0-1 normalized from slider, converted to 0-100 internally)</param>
    public void SetFootstepVolume(float value)
    {
        // Convert 0-1 slider range to 0-100 volume range
        _footstepVolume = Mathf.Clamp(value * 100f, 0f, 100f);

        if (enableDebugLogs)
            Debug.Log($"[SettingsManager] Footstep volume updated to: {_footstepVolume:F1} (Enabled: {_footstepsEnabled})");

        // Only apply to Wwise if footsteps are currently enabled
        if (_footstepsEnabled)
        {
            ApplyFootstepVolumeToWwise();
        }
        else
        {
            if (enableDebugLogs)
                Debug.Log("[SettingsManager] Footsteps disabled, volume stored but not applied to Wwise");
        }
    }

    // ???????????????????????????????????????????????????????????????????????
    // PUBLIC API - FOOTSTEP ENABLED/DISABLED (Called by Toggle Listener)
    // ???????????????????????????????????????????????????????????????????????

    /// <summary>
    /// Enables or disables footstep audio.
    /// Wire this to PageToggleListener.OnToggleChanged in the Inspector.
    /// 
    /// When enabled: Restores the stored volume to Wwise RTPC.
    /// When disabled: Sets Wwise RTPC to 0 (silent) but remembers the volume.
    /// </summary>
    /// <param name="isEnabled">True to enable footsteps, false to disable</param>
    public void SetFootstepEnabled(bool isEnabled)
    {
        _footstepsEnabled = isEnabled;

        if (enableDebugLogs)
            Debug.Log($"[SettingsManager] Footsteps {(isEnabled ? "ENABLED" : "DISABLED")} (Volume: {_footstepVolume:F1})");

        // Apply the combined state to Wwise
        ApplyFootstepVolumeToWwise();
    }

    // ???????????????????????????????????????????????????????????????????????
    // PUBLIC API - FOOTSTEP PITCH (Called by Slider Listener)
    // ???????????????????????????????????????????????????????????????????????

    /// <summary>
    /// Sets the footstep pitch level.
    /// Wire this to PageControlItem.OnValueChanged (slider) in the Inspector.
    /// 
    /// Immediately updates the Wwise RTPC regardless of enabled state.
    /// </summary>
    /// <param name="value">Pitch level (0-1 normalized from slider, converted to 0-100 internally)</param>
    public void SetFootstepPitch(float value)
    {
        // Convert 0-1 slider range to 0-100 pitch range
        _footstepPitch = Mathf.Clamp(value * 100f, 0f, 100f);

        if (enableDebugLogs)
            Debug.Log($"[SettingsManager] Footstep pitch updated to: {_footstepPitch:F1}");

        // Apply to Wwise immediately
        ApplyFootstepPitchToWwise();
    }

    // ???????????????????????????????????????????????????????????????????????
    // PRIVATE METHODS - WWISE APPLICATION LOGIC
    // ???????????????????????????????????????????????????????????????????????

    /// <summary>
    /// Applies the current footstep state to Wwise.
    /// Combines the enabled state and volume: sends stored volume if enabled, 0 if disabled.
    /// </summary>
    private void ApplyFootstepVolumeToWwise()
    {
        if (footstepVolumeRTPC == null || !footstepVolumeRTPC.IsValid())
        {
            if (enableDebugLogs)
                Debug.LogWarning("[SettingsManager] Cannot apply footstep volume: RTPC is invalid");
            return;
        }

        // Combine the two states: If disabled, send 0. If enabled, send stored volume.
        float valueToSend = _footstepsEnabled ? _footstepVolume : 0f;

        footstepVolumeRTPC.SetValue(audioEmitter, valueToSend);

        if (enableDebugLogs)
            Debug.Log($"[SettingsManager] Applied to Wwise RTPC '{footstepVolumeRTPC.Name}': {valueToSend:F1} on '{audioEmitter.name}'");
    }

    /// <summary>
    /// Applies the current footstep pitch to Wwise.
    /// Updates immediately regardless of enabled state.
    /// Maps internal 0-100 range to Wwise -1200 to +1200 range.
    /// </summary>
    private void ApplyFootstepPitchToWwise()
    {
        if (footstepPitchRTPC == null || !footstepPitchRTPC.IsValid())
        {
            if (enableDebugLogs)
                Debug.LogWarning("[SettingsManager] Cannot apply footstep pitch: RTPC is invalid");
            return;
        }

        // Map 0-100 internal range to -1200 to +1200 Wwise range
        // Formula: (value * 2400 / 100) - 1200
        // Simplified: (value * 24) - 1200
        float wwiseValue = (_footstepPitch * 24f) - 1200f;

        footstepPitchRTPC.SetValue(audioEmitter, wwiseValue);

        if (enableDebugLogs)
            Debug.Log($"[SettingsManager] Applied to Wwise RTPC '{footstepPitchRTPC.Name}': {wwiseValue:F1} (from internal {_footstepPitch:F1}) on '{audioEmitter.name}'");
    }

    // ???????????????????????????????????????????????????????????????????????
    // PUBLIC API - GETTERS (Optional - for querying current state)
    // ???????????????????????????????????????????????????????????????????????

    /// <summary>
    /// Gets whether footsteps are currently enabled.
    /// Use this property for quick checks (e.g., in player controllers).
    /// </summary>
    public bool IsFootstepsEnabled => _footstepsEnabled;

    /// <summary>
    /// Gets the currently stored footstep volume (0-100 range).
    /// Useful for initializing UI elements or saving to disk.
    /// </summary>
    public float GetFootstepVolume()
    {
        return _footstepVolume;
    }

    /// <summary>
    /// Gets the currently stored footstep pitch (0-100 range).
    /// Useful for initializing UI elements or saving to disk.
    /// </summary>
    public float GetFootstepPitch()
    {
        return _footstepPitch;
    }

    /// <summary>
    /// Gets whether footsteps are currently enabled.
    /// Useful for initializing UI elements or saving to disk.
    /// </summary>
    public bool GetFootstepsEnabled()
    {
        return _footstepsEnabled;
    }

    /// <summary>
    /// Gets the effective volume being sent to Wwise (accounts for enabled state).
    /// Returns 0 if disabled, stored volume if enabled.
    /// </summary>
    public float GetEffectiveFootstepVolume()
    {
        return _footstepsEnabled ? _footstepVolume : 0f;
    }

