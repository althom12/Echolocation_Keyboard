using UnityEngine;
using UnityEngine.Events;

/// <summary>
/// Generic Toggle Listener for PageControlItem (Data-Driven Settings)
/// 
/// This listener bridges the gap between PageControlItem's float-based OnValueChanged event
/// and boolean-based game settings (VSync, Invert Y-Axis, etc.).
/// 
/// DESIGN PATTERN:
/// This is a "Listener" in the MVC pattern - it responds to Model changes (PageControlItem)
/// and exposes a flexible UnityEvent<bool> that can be wired to any game system.
/// 
/// USAGE:
/// 1. Attach this script to any GameObject in your settings page hierarchy
/// 2. In the Inspector, wire PageControlItem.OnValueChanged to this script's OnValueChanged() method
/// 3. Wire this script's OnToggleChanged event to your target system (e.g., QualitySettings.vSyncCount)
/// 
/// EXAMPLE USE CASES:
/// - VSync Toggle: Wire OnToggleChanged to a method that sets QualitySettings.vSyncCount (1 or 0)
/// - Invert Y-Axis: Wire OnToggleChanged to your PlayerController's invertYAxis field
/// - Subtitles: Wire OnToggleChanged to your SubtitleManager's SetEnabled(bool) method
/// - Motion Blur: Wire OnToggleChanged to your post-processing volume's motionBlur.active
/// 
/// COMPOSITION PATTERN:
/// This script can coexist with UIBinder on the same GameObject:
/// - UIBinder updates the visual toggle checkmark (View)
/// - PageToggleListener updates game systems (Game Logic)
/// Both respond to the same PageControlItem.OnValueChanged event.
/// </summary>
public class PageToggleListener : MonoBehaviour
{
    // ???????????????????????????????????????????????????????????????????????
    // INSPECTOR FIELDS
    // ???????????????????????????????????????????????????????????????????????

    [Header("Boolean Conversion")]
    [Tooltip("Threshold for float-to-bool conversion. Values > this = true, values <= this = false.")]
    [SerializeField] private float trueThreshold = 0.5f;

    [Header("Output Event")]
    [Tooltip("Fired when the boolean state changes. Wire this to your target game system.")]
    public UnityEvent<bool> OnToggleChanged;

    [Header("Debug")]
    [Tooltip("Enable detailed console logging for troubleshooting")]
    [SerializeField] private bool enableDebugLogs = false;

    // ???????????????????????????????????????????????????????????????????????
    // PRIVATE FIELDS
    // ???????????????????????????????????????????????????????????????????????

    private bool currentState = false;
    private bool isInitialized = false;

    // ???????????????????????????????????????????????????????????????????????
    // UNITY LIFECYCLE
    // ???????????????????????????????????????????????????????????????????????

    private void Start()
    {
        isInitialized = true;

        if (enableDebugLogs)
            Debug.Log($"[PageToggleListener - {gameObject.name}] Initialized with threshold: {trueThreshold}");
    }

    // ???????????????????????????????????????????????????????????????????????
    // PUBLIC API - Wire these methods to PageControlItem.OnValueChanged
    // ???????????????????????????????????????????????????????????????????????

    /// <summary>
    /// Main listener method: Converts float to bool and fires OnToggleChanged event.
    /// Wire this to PageControlItem.OnValueChanged in the Inspector.
    /// </summary>
    /// <param name="value">The float value from PageControlItem (0 = false, 1 = true)</param>
    public void OnValueChanged(float value)
    {
        // Don't process changes before initialization
        if (!isInitialized)
        {
            if (enableDebugLogs)
                Debug.LogWarning($"[PageToggleListener - {gameObject.name}] OnValueChanged called before initialization, ignoring");
            return;
        }

        // Convert float to bool using threshold
        bool newState = value > trueThreshold;

        // Only fire event if state actually changed (prevents duplicate calls)
        if (newState != currentState)
        {
            currentState = newState;

            if (enableDebugLogs)
                Debug.Log($"[PageToggleListener - {gameObject.name}] State changed: {value:F2} ? {newState} (threshold: {trueThreshold})");

            // Fire the event for external systems to respond
            OnToggleChanged?.Invoke(newState);
        }
        else if (enableDebugLogs)
        {
            Debug.Log($"[PageToggleListener - {gameObject.name}] State unchanged: {newState} (value: {value:F2})");
        }
    }

    /// <summary>
    /// Alternative method name for clarity when wiring in Inspector.
    /// Functionally identical to OnValueChanged().
    /// </summary>
    public void UpdateToggle(float value)
    {
        OnValueChanged(value);
    }

    // ???????????????????????????????????????????????????????????????????????
    // PUBLIC API - Query Current State
    // ???????????????????????????????????????????????????????????????????????

    /// <summary>
    /// Get the current boolean state without firing events.
    /// Useful for saving settings or querying state from other scripts.
    /// </summary>
    public bool GetCurrentState()
    {
        return currentState;
    }

    // ???????????????????????????????????????????????????????????????????????
    // PUBLIC API - Manual Control (Optional)
    // ???????????????????????????????????????????????????????????????????????

    /// <summary>
    /// Manually set the toggle state without requiring a float input.
    /// Useful for initialization or loading saved settings.
    /// </summary>
    /// <param name="state">The boolean state to set</param>
    /// <param name="fireEvent">Should the OnToggleChanged event fire?</param>
    public void SetState(bool state, bool fireEvent = true)
    {
        if (!isInitialized) return;

        bool oldState = currentState;
        currentState = state;

        if (enableDebugLogs)
            Debug.Log($"[PageToggleListener - {gameObject.name}] State set manually: {oldState} ? {state} (fireEvent: {fireEvent})");

        if (fireEvent && state != oldState)
        {
            OnToggleChanged?.Invoke(state);
        }
    }

    // ???????????????????????????????????????????????????????????????????????
    // DEBUG HELPERS (Editor Only)
    // ???????????????????????????????????????????????????????????????????????

#if UNITY_EDITOR
    private void OnValidate()
    {
        // Clamp threshold to valid range
        if (trueThreshold < 0f)
        {
            Debug.LogWarning($"[PageToggleListener - {gameObject.name}] trueThreshold is negative ({trueThreshold}), clamping to 0");
            trueThreshold = 0f;
        }
        else if (trueThreshold > 1f)
        {
            Debug.LogWarning($"[PageToggleListener - {gameObject.name}] trueThreshold is > 1 ({trueThreshold}), this may cause unexpected behavior");
        }
    }
#endif
}