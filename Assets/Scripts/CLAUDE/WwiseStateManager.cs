using UnityEngine;
using UnityEngine.Events;

/// <summary>
/// Gold Standard Wwise State Manager
/// 
/// Centralized management of Wwise States for pause/resume, UI states, etc.
/// Provides a clean interface for toggling between states and querying current state.
/// 
/// DESIGN PHILOSOPHY:
/// - State Encapsulation: Manages Wwise state groups with type safety
/// - Query Support: Scripts can check current state without coupling to Wwise
/// - Event Broadcasting: Notifies listeners when states change
/// 
/// USE CASES:
/// - Tutorial pause/resume (Playing/Paused states)
/// - UI audio states (Idle/Window_Opening)
/// - Game state audio (Combat/Exploration/Menu)
/// - Any Wwise State Group management
/// 
/// REPLACES:
/// - TutorialAudioController (redundant pause/resume logic)
/// - Scattered AkSoundEngine.SetState() calls
/// </summary>
public class WwiseStateManager : MonoBehaviour
{
    // ???????????????????????????????????????????????????????????????
    // INSPECTOR FIELDS
    // ???????????????????????????????????????????????????????????????

    [Header("State Group Configuration")]
    [Tooltip("The name of the Wwise State Group (e.g., 'Tutorial_State', 'UI_Audio_State')")]
    public string stateGroupName = "Tutorial_State";

    [Header("State Definitions")]
    [Tooltip("The primary state (e.g., 'Playing', 'Idle')")]
    public string primaryStateName = "Playing";

    [Tooltip("The secondary state (e.g., 'Paused', 'Window_Opening')")]
    public string secondaryStateName = "Paused";

    [Header("Initial State")]
    [Tooltip("Which state to set on Start")]
    public bool startInPrimaryState = true;

    [Header("Callbacks")]
    [Tooltip("Invoked when state changes to primary")]
    public UnityEvent onPrimaryStateEntered;

    [Tooltip("Invoked when state changes to secondary")]
    public UnityEvent onSecondaryStateEntered;

    // ???????????????????????????????????????????????????????????????
    // PRIVATE FIELDS
    // ???????????????????????????????????????????????????????????????

    private bool isInPrimaryState = true;

    // ???????????????????????????????????????????????????????????????
    // UNITY LIFECYCLE
    // ???????????????????????????????????????????????????????????????

    private void Start()
    {
        // Validate Wwise initialization
        if (!AkSoundEngine.IsInitialized())
        {
            Debug.LogError($"[WwiseStateManager] '{gameObject.name}': Wwise is not initialized!");
            this.enabled = false;
            return;
        }

        // Set initial state
        if (startInPrimaryState)
        {
            SetToPrimaryState();
        }
        else
        {
            SetToSecondaryState();
        }
    }

    // ???????????????????????????????????????????????????????????????
    // PUBLIC API - State Control
    // ???????????????????????????????????????????????????????????????

    /// <summary>
    /// Sets the Wwise state to the primary state.
    /// </summary>
    public void SetToPrimaryState()
    {
        SetState(primaryStateName);
        isInPrimaryState = true;
        onPrimaryStateEntered?.Invoke();
    }

    /// <summary>
    /// Sets the Wwise state to the secondary state.
    /// </summary>
    public void SetToSecondaryState()
    {
        SetState(secondaryStateName);
        isInPrimaryState = false;
        onSecondaryStateEntered?.Invoke();
    }

    /// <summary>
    /// Toggles between primary and secondary states.
    /// </summary>
    public void ToggleState()
    {
        if (isInPrimaryState)
        {
            SetToSecondaryState();
        }
        else
        {
            SetToPrimaryState();
        }
    }

    /// <summary>
    /// Sets a specific state by name (for advanced use cases).
    /// </summary>
    public void SetStateByName(string stateName)
    {
        if (string.IsNullOrEmpty(stateName))
        {
            Debug.LogWarning($"[WwiseStateManager] '{gameObject.name}': Attempted to set null/empty state name");
            return;
        }

        SetState(stateName);

        // Update internal tracking if it matches known states
        if (stateName == primaryStateName)
        {
            isInPrimaryState = true;
            onPrimaryStateEntered?.Invoke();
        }
        else if (stateName == secondaryStateName)
        {
            isInPrimaryState = false;
            onSecondaryStateEntered?.Invoke();
        }
    }

    // ???????????????????????????????????????????????????????????????
    // PUBLIC API - State Queries
    // ???????????????????????????????????????????????????????????????

    /// <summary>
    /// Checks if currently in primary state.
    /// </summary>
    public bool IsInPrimaryState() => isInPrimaryState;

    /// <summary>
    /// Checks if currently in secondary state.
    /// </summary>
    public bool IsInSecondaryState() => !isInPrimaryState;

    /// <summary>
    /// Gets the current state name.
    /// </summary>
    public string GetCurrentStateName()
    {
        return isInPrimaryState ? primaryStateName : secondaryStateName;
    }

    // ???????????????????????????????????????????????????????????????
    // PRIVATE METHODS
    // ???????????????????????????????????????????????????????????????

    private void SetState(string stateName)
    {
        if (!AkSoundEngine.IsInitialized())
        {
            Debug.LogError($"[WwiseStateManager] '{gameObject.name}': Cannot set state - Wwise not initialized!");
            return;
        }

        AKRESULT result = AkSoundEngine.SetState(stateGroupName, stateName);

        if (result == AKRESULT.AK_Success)
        {
            Debug.Log($"[WwiseStateManager] '{gameObject.name}': Set state '{stateGroupName}' to '{stateName}'");
        }
        else
        {
            Debug.LogError($"[WwiseStateManager] '{gameObject.name}': Failed to set state '{stateName}' in group '{stateGroupName}'. Result: {result}");
            Debug.LogError($"Possible causes:\n" +
                          $"  1. State Group '{stateGroupName}' doesn't exist in Wwise\n" +
                          $"  2. State '{stateName}' doesn't exist in the group\n" +
                          $"  3. SoundBank not loaded\n" +
                          $"  4. State names are case-sensitive - check exact spelling");
        }
    }

    // ???????????????????????????????????????????????????????????????
    // DEBUG HELPERS
    // ???????????????????????????????????????????????????????????????

#if UNITY_EDITOR
    private void OnValidate()
    {
        if (string.IsNullOrEmpty(stateGroupName))
        {
            Debug.LogWarning($"[WwiseStateManager] '{gameObject.name}': stateGroupName is empty!");
        }

        if (string.IsNullOrEmpty(primaryStateName))
        {
            Debug.LogWarning($"[WwiseStateManager] '{gameObject.name}': primaryStateName is empty!");
        }

        if (string.IsNullOrEmpty(secondaryStateName))
        {
            Debug.LogWarning($"[WwiseStateManager] '{gameObject.name}': secondaryStateName is empty!");
        }
    }

    // Optional: Display current state in Inspector
    [ContextMenu("Log Current State")]
    private void LogCurrentState()
    {
        Debug.Log($"[WwiseStateManager] '{gameObject.name}': Current state = {GetCurrentStateName()} (Primary: {isInPrimaryState})");
    }
#endif
}