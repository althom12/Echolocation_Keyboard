using UnityEngine;
using UnityEngine.Events;

/// <summary>
/// Gold Standard Sequential Wwise Event Player
/// 
/// Manages an array of Wwise events that play in sequence.
/// Designed for tutorial systems, narration, or any ordered audio playback.
/// 
/// DESIGN PHILOSOPHY:
/// - State Management: Tracks current index and playback state
/// - Flexible Control: Play next, previous, specific index, or loop through all
/// - Integration Ready: Works with pause/resume systems via WwiseStateManager
/// 
/// USE CASES:
/// - Tutorial instruction playback
/// - Sequential narration
/// - Ordered sound effects
/// - Audio walkthroughs
/// 
/// REPLACES:
/// - TutorialManager's instructionSounds[] array management
/// - Manual index tracking in various scripts
/// </summary>
public class WwiseSequentialEventPlayer : MonoBehaviour
{
    // ???????????????????????????????????????????????????????????????
    // INSPECTOR FIELDS
    // ???????????????????????????????????????????????????????????????

    [Header("Event Sequence")]
    [Tooltip("Array of Wwise events to play in sequence")]
    public AK.Wwise.Event[] events;

    [Tooltip("GameObject to emit sounds from. If null, uses this GameObject.")]
    public GameObject soundEmitter;

    [Header("Playback Options")]
    [Tooltip("Automatically advance to next event when current finishes")]
    public bool autoAdvance = false;

    [Tooltip("Loop back to first event after playing the last one")]
    public bool loopSequence = false;

    [Tooltip("Stop all sounds on emitter before playing each event")]
    public bool stopAllBeforeEachEvent = true;

    [Header("Callbacks")]
    [Tooltip("Invoked when an event starts playing. Passes the index.")]
    public UnityEvent<int> onEventStarted;

    [Tooltip("Invoked when the sequence completes (reaches the end without looping)")]
    public UnityEvent onSequenceComplete;

    // ???????????????????????????????????????????????????????????????
    // PRIVATE FIELDS
    // ???????????????????????????????????????????????????????????????

    private int currentIndex = -1;
    private uint currentPlayingID = AkSoundEngine.AK_INVALID_PLAYING_ID;
    private bool isPlaying = false;

    // ???????????????????????????????????????????????????????????????
    // UNITY LIFECYCLE
    // ???????????????????????????????????????????????????????????????

    private void Awake()
    {
        if (soundEmitter == null)
        {
            soundEmitter = this.gameObject;
        }
    }

    // ???????????????????????????????????????????????????????????????
    // PUBLIC API - Sequential Control
    // ???????????????????????????????????????????????????????????????

    /// <summary>
    /// Plays the first event in the sequence.
    /// </summary>
    public void PlayFromStart()
    {
        PlayAtIndex(0);
    }

    /// <summary>
    /// Plays the next event in the sequence.
    /// If at the end, behavior depends on loopSequence setting.
    /// </summary>
    public void PlayNext()
    {
        int nextIndex = currentIndex + 1;

        if (nextIndex >= events.Length)
        {
            if (loopSequence)
            {
                nextIndex = 0;
            }
            else
            {
                Debug.Log($"[WwiseSequentialEventPlayer] '{gameObject.name}': Reached end of sequence");
                onSequenceComplete?.Invoke();
                return;
            }
        }

        PlayAtIndex(nextIndex);
    }

    /// <summary>
    /// Plays the previous event in the sequence.
    /// If at the start, wraps to end if loopSequence is true.
    /// </summary>
    public void PlayPrevious()
    {
        int prevIndex = currentIndex - 1;

        if (prevIndex < 0)
        {
            if (loopSequence)
            {
                prevIndex = events.Length - 1;
            }
            else
            {
                Debug.LogWarning($"[WwiseSequentialEventPlayer] '{gameObject.name}': Already at start of sequence");
                return;
            }
        }

        PlayAtIndex(prevIndex);
    }

    /// <summary>
    /// Plays a specific event by index.
    /// This is the core playback method used by TutorialManager.
    /// </summary>
    public void PlayAtIndex(int index)
    {
        // Validate index
        if (index < 0 || index >= events.Length)
        {
            Debug.LogError($"[WwiseSequentialEventPlayer] '{gameObject.name}': Index {index} out of range (0-{events.Length - 1})");
            return;
        }

        // Validate event at index
        AK.Wwise.Event eventToPlay = events[index];
        if (eventToPlay == null || !eventToPlay.IsValid())
        {
            Debug.LogWarning($"[WwiseSequentialEventPlayer] '{gameObject.name}': Event at index {index} is null or invalid");
            return;
        }

        // Stop previous event if configured
        if (stopAllBeforeEachEvent)
        {
            StopCurrentEvent();
        }

        // Update index
        currentIndex = index;

        // Post the event
        if (autoAdvance)
        {
            // Register callback to auto-advance
            uint flags = (uint)AkCallbackType.AK_EndOfEvent;
            currentPlayingID = eventToPlay.Post(
                soundEmitter,
                flags,
                OnEventFinished,
                null
            );
        }
        else
        {
            currentPlayingID = eventToPlay.Post(soundEmitter);
        }

        isPlaying = true;

        // Invoke callback
        onEventStarted?.Invoke(currentIndex);

        Debug.Log($"[WwiseSequentialEventPlayer] '{gameObject.name}': Playing event at index {index} ('{eventToPlay.Name}')");
    }

    /// <summary>
    /// Stops the currently playing event.
    /// </summary>
    public void StopCurrentEvent()
    {
        if (currentPlayingID != AkSoundEngine.AK_INVALID_PLAYING_ID)
        {
            AkSoundEngine.StopPlayingID(currentPlayingID);
            currentPlayingID = AkSoundEngine.AK_INVALID_PLAYING_ID;
        }
        else if (stopAllBeforeEachEvent)
        {
            AkSoundEngine.StopAll(soundEmitter);
        }

        isPlaying = false;
    }

    /// <summary>
    /// Resets the sequence to the beginning without playing.
    /// </summary>
    public void Reset()
    {
        StopCurrentEvent();
        currentIndex = -1;
    }

    // ???????????????????????????????????????????????????????????????
    // GETTERS
    // ???????????????????????????????????????????????????????????????

    public int GetCurrentIndex() => currentIndex;
    public int GetEventCount() => events.Length;
    public bool IsPlaying() => isPlaying;

    // ???????????????????????????????????????????????????????????????
    // PRIVATE METHODS
    // ???????????????????????????????????????????????????????????????

    private void OnEventFinished(object in_cookie, AkCallbackType in_type, object in_info)
    {
        if (in_type == AkCallbackType.AK_EndOfEvent)
        {
            currentPlayingID = AkSoundEngine.AK_INVALID_PLAYING_ID;
            isPlaying = false;

            if (autoAdvance)
            {
                PlayNext();
            }
        }
    }

    // ???????????????????????????????????????????????????????????????
    // DEBUG HELPERS
    // ???????????????????????????????????????????????????????????????

#if UNITY_EDITOR
    private void OnValidate()
    {
        if (events == null || events.Length == 0)
        {
            Debug.LogWarning($"[WwiseSequentialEventPlayer] '{gameObject.name}': events array is empty!");
        }

        if (soundEmitter == null)
        {
            soundEmitter = this.gameObject;
        }
    }
#endif
}