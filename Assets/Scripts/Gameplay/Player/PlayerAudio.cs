using UnityEngine;

/// <summary>
/// Player Audio Controller
/// 
/// Manages all player-related audio including:
/// - Echolocation clicks (with pitch adjustment)
/// - Footstep sounds (controlled by SettingsManager)
/// - Collision sounds with cooldown
/// 
/// AUDIO SYSTEMS:
/// - Echolocation: Mouse button 0 (left click)
/// - Pitch Adjustment: Mouse button 2 (middle click) to enter mode, scroll wheel to adjust
/// - Footsteps: Automatically triggered by movement, respects SettingsManager.IsFootstepsEnabled
/// - Collisions: Triggered on collision with "Wall" or "Obstacle" tags, has cooldown
/// 
/// INPUT SYSTEM:
/// Uses mixed Legacy Input (Input.GetMouseButton) and is compatible with the existing codebase.
/// This is intentional and should not be converted unless specifically requested.
/// </summary>
public class PlayerAudio : MonoBehaviour
{
    // ???????????????????????????????????????????????????????????
    // INSPECTOR FIELDS - WWISE EMITTERS
    // ???????????????????????????????????????????????????????????

    [Header("Wwise Emitters")]
    [Tooltip("GameObject that emits echolocation click sounds")]
    public GameObject ClickEmitter;

    [Tooltip("GameObject that emits footstep sounds")]
    public GameObject FootstepEmitter;

    // ???????????????????????????????????????????????????????????
    // INSPECTOR FIELDS - WWISE EVENTS
    // ???????????????????????????????????????????????????????????

    [Header("Wwise Events")]
    [Tooltip("The main echolocation click sound")]
    public AK.Wwise.Event EcholocationSound;

    [Tooltip("Footstep sound event")]
    public AK.Wwise.Event FootstepSound;

    [Tooltip("Plays when pitch adjustment mode is activated")]
    public AK.Wwise.Event PA_Settings_Opened;

    [Tooltip("Plays when pitch adjustments are confirmed/closed")]
    public AK.Wwise.Event PA_Settings_Confirmed;

    [Tooltip("Collision impact sound")]
    public AK.Wwise.Event CollisionSound;

    // ???????????????????????????????????????????????????????????
    // INSPECTOR FIELDS - WWISE RTPCS
    // ???????????????????????????????????????????????????????????

    [Header("Wwise RTPCs")]
    [Tooltip("The EXACT name of the Pitch RTPC in your Wwise project (e.g., 'click_pitch')")]
    public string ClickPitchRTPC_Name = "click_pitch";

    // ???????????????????????????????????????????????????????????
    // INSPECTOR FIELDS - SETTINGS
    // ???????????????????????????????????????????????????????????

    [Header("Footstep Settings")]
    [Tooltip("Time interval between footstep sounds (in seconds)")]
    public float FootstepInterval = 0.5f;

    [Header("Collision Settings")]
    [Tooltip("How long to wait (in seconds) before another collision sound can play")]
    public float CollisionCooldown = 5.0f;

    [Header("Echolocation Pitch Settings")]
    [Tooltip("How quickly the scroll wheel adjusts the pitch")]
    [SerializeField] private float scrollSensitivity = 500f;

    // ???????????????????????????????????????????????????????????
    // PRIVATE FIELDS - STATE
    // ???????????????????????????????????????????????????????????

    /// <summary>
    /// Control state for pitch adjustment mode
    /// </summary>
    private enum ControlState { Normal, AdjustingPitch }
    private ControlState _currentState = ControlState.Normal;

    /// <summary>
    /// Current pitch value for echolocation clicks (-1200 to +1200)
    /// </summary>
    private float _currentPitchValue = 0f;

    /// <summary>
    /// Timer for footstep interval tracking
    /// </summary>
    private float _footstepTimer;

    /// <summary>
    /// Timer for collision sound cooldown
    /// </summary>
    private float _collisionCooldownTimer;

    // ???????????????????????????????????????????????????????????
    // UNITY LIFECYCLE
    // ???????????????????????????????????????????????????????????

    private void Start()
    {
        // Set default emitters if not assigned
        if (ClickEmitter == null) ClickEmitter = this.gameObject;
        if (FootstepEmitter == null) FootstepEmitter = this.gameObject;

        // Initialize pitch RTPC to default value
        if (!string.IsNullOrEmpty(ClickPitchRTPC_Name))
        {
            AkSoundEngine.SetRTPCValue(ClickPitchRTPC_Name, _currentPitchValue);
        }

        // Initialize footstep timer
        _footstepTimer = FootstepInterval;
    }

    private void Update()
    {
        // Echolocation click input (left mouse button)
        if (Input.GetMouseButtonDown(0))
        {
            if (_currentState == ControlState.Normal)
            {
                EcholocationSound?.Post(ClickEmitter);
            }
        }

        // Handle pitch adjustment input (middle mouse button + scroll wheel)
        

        // Update collision cooldown timer
        if (_collisionCooldownTimer > 0)
        {
            _collisionCooldownTimer -= Time.deltaTime;
        }
    }

    private void OnControllerColliderHit(ControllerColliderHit hit)
    {
        // Check if the cooldown is over AND if the object has either the "Wall" OR "Obstacle" tag
        if (_collisionCooldownTimer <= 0 && (hit.gameObject.CompareTag("Wall") || hit.gameObject.CompareTag("Obstacle")))
        {
            CollisionSound?.Post(gameObject);
            _collisionCooldownTimer = CollisionCooldown;
        }
    }

    // ???????????????????????????????????????????????????????????
    // PITCH ADJUSTMENT SYSTEM
    // ???????????????????????????????????????????????????????????

    /// <summary>
    /// Handles pitch adjustment mode toggling and scroll wheel input.
    /// Middle mouse button toggles the mode, scroll wheel adjusts pitch.
    /// </summary>
   

    // ???????????????????????????????????????????????????????????
    // FOOTSTEP SYSTEM
    // ???????????????????????????????????????????????????????????

    /// <summary>
    /// Handles footstep audio playback based on player movement.
    /// Called by the player controller (FirstPersonController).
    /// Respects the SettingsManager.IsFootstepsEnabled setting.
    /// </summary>
    /// <param name="isMoving">True if player is currently moving, false otherwise</param>
    public void HandleFootsteps(bool isMoving)
    {
        // Check if footsteps are disabled in settings
        if (SettingsManager.Instance != null && !SettingsManager.Instance.IsFootstepsEnabled)
        {
            _footstepTimer = FootstepInterval; // Reset timer to prevent immediate step if re-enabled while moving
            return; // Stop processing footsteps for this frame
        }

        if (isMoving)
        {
            _footstepTimer += Time.deltaTime;
            if (_footstepTimer >= FootstepInterval)
            {
                FootstepSound?.Post(FootstepEmitter);
                _footstepTimer = 0f;
            }
        }
        else
        {
            _footstepTimer = FootstepInterval;
        }
    }

    // ???????????????????????????????????????????????????????????
    // PUBLIC API
    // ???????????????????????????????????????????????????????????

    /// <summary>
    /// Resets the pitch RTPC to default value (0).
    /// Called by TutorialManager when ending the tutorial.
    /// </summary>
    public void ResetPitchRTPC()
    {
        _currentPitchValue = 0f;
        if (!string.IsNullOrEmpty(ClickPitchRTPC_Name))
        {
            AkSoundEngine.SetRTPCValue(ClickPitchRTPC_Name, _currentPitchValue);
            Debug.Log("[PlayerAudio] Pitch RTPC has been reset to default.");
        }
    }
}